"""Smoke tests for the openqbw package on the synthetic fixtures.

The fixtures are generated by crates/openqbw/tests/common/mod.rs; no real
company file is involved.
"""

import inspect
import pathlib
import warnings

import pytest

import openqbw

DATA = pathlib.Path(__file__).resolve().parents[2] / "openqbw" / "tests" / "data"
GOOD = DATA / "synthetic.qbw"
BAD = DATA / "synthetic-bad-record.qbw"


def test_exception_hierarchy():
    assert issubclass(openqbw.OpenQBWError, ValueError)
    assert issubclass(openqbw.OpenQBWIOError, openqbw.OpenQBWError)
    assert issubclass(openqbw.OpenQBWIOError, OSError)
    assert issubclass(openqbw.FormatError, openqbw.OpenQBWError)
    assert issubclass(openqbw.RecordError, openqbw.FormatError)
    assert issubclass(openqbw.ContentError, openqbw.FormatError)
    assert issubclass(openqbw.OpenQBWWarning, UserWarning)


def test_options_are_keyword_only():
    with pytest.raises(TypeError):
        openqbw.open(GOOD, True)


def test_reads_the_synthetic_file():
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        r = openqbw.open(GOOD)
        lines = r.line_items()
        txns = r.transactions()
        tables = r.tables()
    assert r.page_count == 8
    assert r.file_size == 8 * 4096
    assert r.attribution_gap is None
    assert not r.lenient
    assert [t.name for t in tables] == [
        "abmc_invoice_header",
        "abmc_invoice_inventory_lineitem",
        "abmc_general_journal_inventory_lineitem",
    ]
    assert len(lines) == 4
    assert lines.rejected == []
    assert [li.amount_cents for li in lines] == [266048, 266112, 77120, -77120]
    assert lines[2].amount_encoding == "sign_bit_u23"
    assert lines[0].amount_raw == bytes([0x02, 0x40, 0x0F, 0x04])
    assert lines[0].txn_date_days_since_unix == 19800
    assert lines[0].to_dict()["invoice_id"] == "0000000000001QBm"
    assert [t.txn_type for t in txns] == ["invoice"]
    assert "header_id_ambiguous" in txns[0].flags


def test_undecodable_record_raises_unless_lenient():
    r = openqbw.open(BAD)
    with pytest.raises(openqbw.RecordError) as exc:
        r.line_items()
    assert exc.value.kind == "unknown_amount_type"
    assert exc.value.page_number == 7

    r = openqbw.open(BAD, lenient=True)
    with pytest.warns(openqbw.OpenQBWWarning):
        lines = r.line_items()
    assert len(lines) == 4
    assert [x.kind for x in lines.rejected] == ["unknown_amount_type"]


def test_missing_file_is_an_os_error(tmp_path):
    with pytest.raises(OSError) as exc:
        openqbw.open(tmp_path / "missing.qbw")
    assert isinstance(exc.value, openqbw.OpenQBWIOError)
    assert exc.value.kind == "io"
    assert exc.value.filename is not None


def test_not_a_company_file_is_a_format_error(tmp_path):
    p = tmp_path / "zeros.qbw"
    p.write_bytes(bytes(8192))
    with pytest.raises(openqbw.FormatError) as exc:
        openqbw.open(p)
    assert exc.value.kind == "bad_magic"


def test_public_names_have_stubs():
    stub = (pathlib.Path(openqbw.__file__).parent / "_openqbw.pyi").read_text()
    for name in openqbw.__all__:
        obj = getattr(openqbw, name)
        if inspect.isclass(obj) and obj.__module__ == "openqbw._errors":
            continue
        if name == "__version__":
            continue
        assert f"class {name}" in stub or f"def {name}" in stub, name
    assert (pathlib.Path(openqbw.__file__).parent / "py.typed").exists()
